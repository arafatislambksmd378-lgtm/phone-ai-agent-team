"""GitHub-centric execution: task branches, per-agent commits, PR. Repo isolation mandatory."""
from __future__ import annotations
from integrations.github.api import GitHubAPI
class GitHubExecutionService:
    def __init__(self, db, api: GitHubAPI, approvals=None): self.db, self.api, self.approvals = db, api, approvals
    def prepare_branch(self, project_id, task_id):
        b=self.db.get_repository(project_id)
        if not b: return {"ok": False, "error": "Connect a GitHub repository to this project first"}
        branch=f"agent/{project_id.replace('proj_','')}/{task_id.replace('task_','')}"
        r=self.api.create_branch(b["repo_full_name"], branch, b["default_branch"])
        return {"ok": r.get("ok", False), "branch": branch, "repo": b["repo_full_name"], "api": r}
    def commit_file(self, project_id, task_id, agent_id, branch, path, content):
        b=self.db.assert_repo(project_id, self.db.get_repository(project_id)["repo_full_name"])  # binding re-check
        existing=self.api.get_file(b["repo_full_name"], path, branch)
        sha=existing.get("data",{}).get("sha") if existing.get("ok") else None
        return self.api.put_file(b["repo_full_name"], path, content, f"{agent_id}: {task_id} {path}", branch, sha)
    def open_pull_request(self, project_id, task_id, branch, title, agent_summary="", test_results=""):
        b=self.db.get_repository(project_id)
        body=f"Task: {task_id}\n\nAgents: {agent_summary}\n\nTests: {test_results}\n\nGenerated by Phone AI Agent Team."
        r=self.api.create_pr(b["repo_full_name"], title, branch, b["default_branch"], body)
        if r.get("ok"):
            d=r["data"]; self.db.record_pull_request(project_id, b["repo_full_name"], d.get("number"), title, branch, b["default_branch"], d.get("html_url",""), task_id)
        return r
    def merge(self, project_id, number, approval_id):
        b=self.db.get_repository(project_id)
        if self.approvals is not None:
            ok, why = self.approvals.verify(approval_id, project_id=project_id, action="git_push", consume=True)
            if not ok: return {"ok": False, "error": f"Merge blocked: {why}"}
        return self.api.merge_pr(b["repo_full_name"], number)
