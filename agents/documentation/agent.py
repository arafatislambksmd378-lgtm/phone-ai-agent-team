"""Agent 14 — Documentation: README assembled from the real generated artifacts."""
from __future__ import annotations

from agents.base import AgentResult, BaseAgent
from agents.helpers import title_from

SYSTEM = """You are a technical writer. Produce a README.md for the described project:
what it is, how to run it, API table, project layout, troubleshooting. Concise."""


class Agent(BaseAgent):
    agent_id = "documentation"
    name = "Technical Documentation Agent"
    description = "Writes README and guides from the actual project state."
    system_prompt = SYSTEM

    def run(self, task: dict) -> AgentResult:
        title = title_from(self._read("docs/requirements.md"))
        files = self._list()
        api_present = "backend/app.py" in files
        frontend_present = "frontend/index.html" in files
        schema_present = "database/schema.sql" in files
        fallback = f"""# {title}

Generated by the Phone AI Agent Team (16-agent pipeline).

## What it is
A small task app: static frontend, JSON API, SQLite storage. Standard library only —
it runs on Android/Termux with no Docker, no external database and no build step.

## Quick start
```sh
sh scripts/run.sh
# then open http://127.0.0.1:8000
```

## API
| Method | Path | Body | Result |
|---|---|---|---|
| GET | `/api/health` | — | `{{"status":"ok"}}` |
| GET | `/api/items` | — | `{{"items":[...]}}` |
| POST | `/api/items` | `{{"title":"…"}}` | created item |
| DELETE | `/api/items/{{id}}` | — | `{{"deleted":true}}` |

## Tests
```sh
python3 -m pytest -q
```

## Layout
```
backend/    HTTP API + adapters
frontend/   index.html (static SPA)
database/   schema.sql + migrate.py
tests/      pytest suite
docs/       requirements, architecture, security, review, release notes
scripts/    run.sh
```

## Status of this build
- Backend: {'present' if api_present else 'MISSING'}
- Frontend: {'present' if frontend_present else 'MISSING'}
- Database schema: {'present' if schema_present else 'MISSING'}

## Troubleshooting
| Symptom | Fix |
|---|---|
| `Address already in use` | `PORT=8080 sh scripts/run.sh` |
| Empty list in UI | Check `/api/health`; confirm `app.db` is writable |
| `pytest: command not found` | `pip install pytest` inside the venv |
"""
        gen = self.generate(
            f"Project: {title}. Files: {', '.join(files[:40])}\n\nRequirements:\n"
            f"{self._read('docs/requirements.md')[:4000]}\n\nWrite README.md.",
            fallback)
        self._write("README.md", gen.text)
        self._write("docs/troubleshooting.md",
                    "# Troubleshooting\n\n"
                    "| Symptom | Cause | Fix |\n|---|---|---|\n"
                    "| Port 8000 busy | Another process | `PORT=8080 sh scripts/run.sh` |\n"
                    "| `database is locked` | Second writer | Stop the other process; WAL allows one writer |\n"
                    "| Blank page | Backend not running | Start `scripts/run.sh`, then reload |\n"
                    "| Tests import error | Wrong cwd | Run `python3 -m pytest -q` from the project root |\n")
        return AgentResult(ok=True, summary=f"README + troubleshooting written ({gen.mode})",
                           files=["README.md", "docs/troubleshooting.md"], mode=gen.mode,
                           error=gen.error)
