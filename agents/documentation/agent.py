"""Agent 14 — Technical Documentation Agent: README & troubleshooting grounded in real workspace state."""
from __future__ import annotations

from agents.base import AgentResult, BaseAgent
from agents.documentation.prompts import SYSTEM_PROMPT, build_user_prompt
from agents.helpers import primary_entity_from, title_from


class Agent(BaseAgent):
    agent_id = "documentation"
    name = "Technical Documentation Agent"
    description = "Produces accurate README.md and docs/troubleshooting.md from real project files."
    responsibilities = [
        "Inspect actual generated workspace files and upstream handoffs before writing documentation",
        "Document exact run, usage, and pytest commands matching the software category",
        "Write actionable troubleshooting guidance in docs/troubleshooting.md",
    ]
    system_prompt = SYSTEM_PROMPT
    allowed_tools = {"read_file", "write_file", "list_files", "ai_generate"}
    output_schema = {
        "required_files_any": ["README.md", "docs/troubleshooting.md"],
        "required_data_keys": ["software_type", "documented_files"],
    }
    completion_criteria = ["README.md and docs/troubleshooting.md written accurately"]

    def execute(self, task: dict) -> AgentResult:
        ctx = self.build_context(task, extra_files=["docs/requirements.json"])
        title = ctx["spec"].get("project_title") or title_from(ctx["requirements"])
        software_type = ctx["software_type"]
        entity, _ = primary_entity_from(ctx["entities"], ctx["requirements"])
        files = self._list()

        fallback = self._fallback_readme(title, software_type, entity, files, ctx["platform_limitations"])
        prompt = build_user_prompt(
            title=title,
            software_type=software_type,
            files=files,
            spec_md=ctx["requirements"],
            limitations=ctx["platform_limitations"],
        )
        gen = self.generate(prompt, fallback)
        self._write("README.md", gen.text if "#" in gen.text else fallback)

        self._write(
            "docs/troubleshooting.md",
            "# Troubleshooting\n\n"
            "| Symptom | Cause | Fix |\n|---|---|---|\n"
            "| Port 8000 busy | Another local server is bound | `PORT=8080 sh scripts/run.sh` |\n"
            "| `database is locked` | Concurrent write outside WAL timeout | Close duplicate server processes |\n"
            "| `No module named pytest` | Virtualenv not active | Activate `.venv` or run `pip install pytest` |\n"
            "| Android SDK missing on Termux | 3 GB RAM phone lacks full SDK | Run `python3 -m pytest -q` locally or use approved CI |\n",
        )
        return AgentResult(
            ok=True,
            summary=f"README + troubleshooting written for {software_type} ({gen.mode})",
            files=["README.md", "docs/troubleshooting.md"],
            data={"software_type": software_type, "documented_files": len(files)},
            mode=gen.mode,
            error=gen.error,
        )

    @staticmethod
    def _fallback_readme(title: str, software_type: str, entity: str,
                         files: list[str], limitations: list[str]) -> str:
        usage_block = {
            "cli_tool": "```sh\npython3 cli/main.py add \"First item\"\npython3 cli/main.py list --json\n```",
            "python_library": "```sh\nPYTHONPATH=src python3 -m pytest -q\n```",
            "android_app": "```sh\nsh scripts/run.sh   # runs local manifest/domain verification or Gradle if SDK present\n```",
            "desktop_app": "```sh\npython3 desktop/app.py                 # GUI when DISPLAY is set\npython3 desktop/app.py --headless-check # Termux headless verification\n```",
        }.get(
            software_type,
            f"```sh\nsh scripts/run.sh\n# Serves http://127.0.0.1:8000 (API: /api/health, /api/{entity}, /api/items)\n```",
        )
        lims = ("\n## Platform Constraints\n" + "\n".join(f"- {x}" for x in limitations) + "\n") if limitations else ""
        file_tree = "\n".join(f"  {f}" for f in files[:25])
        return f"""# {title}

Generated by the **Phone AI Agent Team** (`{software_type}` workflow).

## Quick Start
{usage_block}

## Automated Tests
```sh
python3 -m pytest -q
```

## Workspace Files
```text
{file_tree}
```
{lims}
## Documentation
- `docs/requirements.md` — Specification
- `docs/architecture.md` — System Design
- `docs/security.md` — Security Audit
- `docs/test-report.md` — Test Execution Verdict
- `docs/troubleshooting.md` — Common Fixes
"""
